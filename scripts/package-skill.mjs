#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const THIS_DIR = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(THIS_DIR, '..');
export const SKILL_ID = 'agentready';
export const SKILL_DIR = path.join(REPO_ROOT, 'skills', SKILL_ID);

/**
 * Canonical source -> packaged skill destination map.
 * Every runtime, license, and synced reference file in skills/agentready/
 * is generated exclusively from these canonical repository sources.
 */
export const PACKAGED_FILE_MAP = Object.freeze([
  ['bin/agentready.mjs', 'scripts/bin/agentready.mjs'],
  ['src/adapters.mjs', 'scripts/src/adapters.mjs'],
  ['src/commerce-model.mjs', 'scripts/src/commerce-model.mjs'],
  ['src/core.mjs', 'scripts/src/core.mjs'],
  ['src/webmcp-products.js', 'scripts/src/webmcp-products.js'],
  ['src/webmcpify-runtime.js', 'scripts/src/webmcpify-runtime.js'],
  ['src/integrations/agentmarkup-next.mjs', 'scripts/src/integrations/agentmarkup-next.mjs'],
  ['LICENSE', 'LICENSE'],
  ['THIRD_PARTY_NOTICES.md', 'THIRD_PARTY_NOTICES.md'],
  ['docs/COMMERCE_VARIANTS.md', 'references/COMMERCE_VARIANTS.md']
]);

function sha256(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

function normalizeLineEndings(buf) {
  return Buffer.from(buf.toString('utf8').replace(/\r\n/g, '\n'), 'utf8');
}

function buildRuntimePackageJson(rootPkg) {
  return `${JSON.stringify(
    {
      name: 'agentready-skill-runtime',
      version: rootPkg.version,
      private: true,
      type: 'module',
      description: 'Self-contained ESM runtime for the portable AgentReady B2A Agent Skill.',
      engines: rootPkg.engines || { node: '>=20' },
      license: rootPkg.license || 'MIT'
    },
    null,
    2
  )}\n`;
}

function buildPortableEntrypoint() {
  return `#!/usr/bin/env node\n// Generated by scripts/package-skill.mjs — do not edit manually.\nimport './bin/agentready.mjs';\n`;
}

/**
 * Parses and validates SKILL.md YAML frontmatter against https://agentskills.io/specification.
 */
export function parseAndValidateSkillFrontmatter(markdown, expectedDirName = SKILL_ID) {
  const errors = [];
  const normalized = String(markdown || '').replace(/\r\n/g, '\n');
  const match = normalized.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) {
    return {
      ok: false,
      errors: ['SKILL.md must begin with a valid YAML frontmatter block delimited by --- lines.'],
      frontmatter: null,
      body: ''
    };
  }

  const rawYaml = match[1];
  const body = match[2];
  const frontmatter = {};
  let currentMapKey = null;

  for (const rawLine of rawYaml.split('\n')) {
    if (!rawLine.trim() || rawLine.trim().startsWith('#')) continue;
    const nested = rawLine.match(/^  ([a-zA-Z0-9_-]+):\s*(.*)$/);
    if (nested && currentMapKey) {
      const val = nested[2].trim().replace(/^["']|["']$/g, '');
      frontmatter[currentMapKey][nested[1]] = val;
      continue;
    }
    currentMapKey = null;
    const top = rawLine.match(/^([a-zA-Z0-9_-]+):\s*(.*)$/);
    if (!top) {
      errors.push(`Unrecognized frontmatter line: "${rawLine}"`);
      continue;
    }
    const key = top[1];
    const value = top[2].trim();
    if (value === '') {
      frontmatter[key] = {};
      currentMapKey = key;
    } else {
      frontmatter[key] = value.replace(/^["']|["']$/g, '');
    }
  }

  // Validate required `name` field per https://agentskills.io/specification
  const name = frontmatter.name;
  if (typeof name !== 'string' || name.length === 0) {
    errors.push('Missing required frontmatter field: name.');
  } else {
    if (name.length > 64) errors.push('Frontmatter name must be 1-64 characters.');
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
      errors.push('Frontmatter name must contain only lowercase alphanumeric characters and single hyphens, without leading/trailing hyphens.');
    }
    if (expectedDirName && name !== expectedDirName) {
      errors.push(`Frontmatter name "${name}" must match parent directory name "${expectedDirName}".`);
    }
  }

  // Validate required `description` field
  const description = frontmatter.description;
  if (typeof description !== 'string' || description.trim().length === 0) {
    errors.push('Missing required frontmatter field: description.');
  } else if (description.length > 1024) {
    errors.push('Frontmatter description must be 1-1024 characters.');
  }

  // Validate optional `compatibility` field
  if (frontmatter.compatibility !== undefined) {
    if (typeof frontmatter.compatibility !== 'string' || frontmatter.compatibility.length === 0 || frontmatter.compatibility.length > 500) {
      errors.push('Frontmatter compatibility must be 1-500 characters when provided.');
    }
  }

  // Validate optional `metadata` mapping (string keys -> string values)
  if (frontmatter.metadata !== undefined) {
    if (typeof frontmatter.metadata !== 'object' || frontmatter.metadata === null || Array.isArray(frontmatter.metadata)) {
      errors.push('Frontmatter metadata must be a string-to-string key-value map.');
    } else {
      for (const [k, v] of Object.entries(frontmatter.metadata)) {
        if (typeof v !== 'string') {
          errors.push(`Frontmatter metadata.${k} must be a string.`);
        }
      }
    }
  }

  // Progressive disclosure recommendation: keep SKILL.md under 500 lines
  const lineCount = normalized.split('\n').length;
  if (lineCount > 500) {
    errors.push(`SKILL.md has ${lineCount} lines, exceeding the 500-line specification guideline.`);
  }

  return {
    ok: errors.length === 0,
    errors,
    frontmatter,
    body,
    lineCount
  };
}

async function listFilesRecursive(dir, baseDir = dir) {
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch (err) {
    if (err.code === 'ENOENT') return [];
    throw err;
  }
  const results = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...(await listFilesRecursive(full, baseDir)));
    } else if (entry.isFile()) {
      results.push(path.relative(baseDir, full).replace(/\\/g, '/'));
    }
  }
  return results.sort();
}

/**
 * Computes the expected packaged files and deterministic manifest from canonical sources.
 */
export async function computeExpectedSkillPackage(repoRoot = REPO_ROOT) {
  const rootPkg = JSON.parse(await fs.readFile(path.join(repoRoot, 'package.json'), 'utf8'));
  const expectedFiles = new Map();
  const manifestEntries = {};

  for (const [srcRel, destRel] of PACKAGED_FILE_MAP) {
    const srcAbs = path.join(repoRoot, srcRel);
    const raw = await fs.readFile(srcAbs);
    const content = normalizeLineEndings(raw);
    expectedFiles.set(destRel, content);
    manifestEntries[destRel] = {
      source: srcRel,
      sha256: sha256(content),
      bytes: content.length
    };
  }

  const runtimePkgBuf = Buffer.from(buildRuntimePackageJson(rootPkg), 'utf8');
  expectedFiles.set('scripts/package.json', runtimePkgBuf);
  manifestEntries['scripts/package.json'] = {
    source: 'generated:package.json',
    sha256: sha256(runtimePkgBuf),
    bytes: runtimePkgBuf.length
  };

  const entryBuf = Buffer.from(buildPortableEntrypoint(), 'utf8');
  expectedFiles.set('scripts/agentready.mjs', entryBuf);
  manifestEntries['scripts/agentready.mjs'] = {
    source: 'generated:entrypoint',
    sha256: sha256(entryBuf),
    bytes: entryBuf.length
  };

  const sortedFiles = {};
  for (const key of Object.keys(manifestEntries).sort()) {
    sortedFiles[key] = manifestEntries[key];
  }

  const manifestObj = {
    schemaVersion: '1.0.0',
    skillId: SKILL_ID,
    packageVersion: rootPkg.version,
    generator: 'scripts/package-skill.mjs',
    files: sortedFiles
  };
  const manifestBuf = Buffer.from(`${JSON.stringify(manifestObj, null, 2)}\n`, 'utf8');
  expectedFiles.set('scripts/.package-manifest.json', manifestBuf);

  return { expectedFiles, manifest: manifestObj };
}

/**
 * Packages canonical sources into skills/agentready/ reproducibly.
 */
export async function packageSkill(repoRoot = REPO_ROOT) {
  const skillDir = path.join(repoRoot, 'skills', SKILL_ID);
  const scriptsDir = path.join(skillDir, 'scripts');
  const { expectedFiles, manifest } = await computeExpectedSkillPackage(repoRoot);

  // Clean managed scripts/ directory so no stale runtime files survive
  await fs.rm(scriptsDir, { recursive: true, force: true });

  const written = [];
  for (const [relPath, buf] of expectedFiles.entries()) {
    const absTarget = path.join(skillDir, relPath);
    await fs.mkdir(path.dirname(absTarget), { recursive: true });
    await fs.writeFile(absTarget, buf);
    written.push(relPath);
  }

  return {
    ok: true,
    skillDir,
    written: written.sort(),
    fileCount: written.length,
    manifest
  };
}

/**
 * Verifies that skills/agentready/ is up to date with canonical sources,
 * has zero stale files in scripts/, and has valid SKILL.md metadata.
 */
export async function checkSkillPackage(repoRoot = REPO_ROOT) {
  const skillDir = path.join(repoRoot, 'skills', SKILL_ID);
  const { expectedFiles } = await computeExpectedSkillPackage(repoRoot);
  const errors = [];

  // 1. Validate SKILL.md
  const skillMdPath = path.join(skillDir, 'SKILL.md');
  try {
    const skillMd = await fs.readFile(skillMdPath, 'utf8');
    const validation = parseAndValidateSkillFrontmatter(skillMd, SKILL_ID);
    if (!validation.ok) {
      errors.push(...validation.errors.map((e) => `SKILL.md: ${e}`));
    }
  } catch (err) {
    errors.push(`Missing SKILL.md: ${err.message}`);
  }

  // 2. Verify every expected file matches canonical source byte-for-byte
  for (const [relPath, expectedBuf] of expectedFiles.entries()) {
    const absPath = path.join(skillDir, relPath);
    try {
      const actualBuf = normalizeLineEndings(await fs.readFile(absPath));
      if (!actualBuf.equals(expectedBuf)) {
        errors.push(`Stale or modified packaged file: skills/${SKILL_ID}/${relPath} (run "npm run skill:package").`);
      }
    } catch {
      errors.push(`Missing packaged file: skills/${SKILL_ID}/${relPath} (run "npm run skill:package").`);
    }
  }

  // 3. Detect stale/unmanaged files inside skills/agentready/scripts/
  const actualScriptFiles = (await listFilesRecursive(path.join(skillDir, 'scripts'))).map(
    (f) => `scripts/${f}`
  );
  for (const actual of actualScriptFiles) {
    if (!expectedFiles.has(actual)) {
      errors.push(`Unexpected stale file in packaged runtime: skills/${SKILL_ID}/${actual}`);
    }
  }

  return {
    ok: errors.length === 0,
    errors,
    checkedFileCount: expectedFiles.size
  };
}

// CLI execution when invoked directly
const isDirectRun =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isDirectRun) {
  const checkOnly = process.argv.includes('--check');
  try {
    if (checkOnly) {
      const res = await checkSkillPackage(REPO_ROOT);
      console.log(JSON.stringify(res, null, 2));
      if (!res.ok) process.exitCode = 1;
    } else {
      const res = await packageSkill(REPO_ROOT);
      const check = await checkSkillPackage(REPO_ROOT);
      console.log(JSON.stringify({ ...res, checkOk: check.ok, checkErrors: check.errors }, null, 2));
      if (!check.ok) process.exitCode = 1;
    }
  } catch (err) {
    console.error('[package-skill]', err.message);
    process.exitCode = 1;
  }
}
